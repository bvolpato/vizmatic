import { access, copyFile, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'fs/promises'
import { spawn } from 'child_process'
import { cpus, tmpdir } from 'os'
import { basename, join } from 'path'
import { exampleTitle, listGalleryExamples } from './gallery-examples'

const examplesDir = 'examples'
const examplesReadmePath = join(examplesDir, 'README.md')
const outDir = 'docs/assets/examples'
const galleryAssetUrl = 'https://bvolpato.github.io/vizmatic/assets/examples'
const themes = ['dark', 'light'] as const
const examples = await listGalleryExamples()
const onlyArgument = process.argv.slice(2).find((argument) => argument.startsWith('--only='))
const selected = onlyArgument ? new Set(onlyArgument.slice(7).split(',').filter(Boolean)) : undefined
if (selected) {
    const names = new Set(examples.map((example) => example.name))
    if (!selected.size || [...selected].some((name) => !names.has(name))) {
        throw new Error('--only requires comma-separated example names without the .tsx extension')
    }
}

const manifest: Array<{ name: string; source: string; outputs: string[] }> = []
const animatedSources: string[] = []
const regularSources: string[] = []
const ncclSources: string[] = []
const transparentSources: string[] = []

function previewFor(outputs: string[], theme: (typeof themes)[number]): string {
    return outputs.find((output) => output.endsWith(`_${theme}.gif`))
        ?? outputs.find((output) => output.endsWith(`_${theme}.png`))
        ?? outputs[0]
        ?? ''
}

function generateExamplesReadme(entries: typeof manifest): string {
    const rows = entries.map((entry) => {
        const title = exampleTitle(entry.name)
        const sourceFile = basename(entry.source)
        const dark = previewFor(entry.outputs, 'dark')
        const light = previewFor(entry.outputs, 'light')

        return `| [${title}](${sourceFile}) | <picture><source media="(prefers-color-scheme: dark)" srcset="${galleryAssetUrl}/${dark}" /><source media="(prefers-color-scheme: light)" srcset="${galleryAssetUrl}/${light}" /><img src="${galleryAssetUrl}/${light}" alt="${title} preview" width="720" /></picture> |`
    })

    return [
        '# Vizmatic examples',
        '',
        'Generated by `pnpm render:examples`. Edit the `.tsx` sources, then run that command again to refresh these previews.',
        '',
        'Rendered assets live on the [Vizmatic gallery](https://bvolpato.github.io/vizmatic/#gallery).',
        '',
        '| Example | Preview |',
        '|---|---|',
        ...rows,
        '',
    ].join('\n')
}

function runCli(args: string[]): Promise<void> {
    return new Promise((resolve, reject) => {
        const child = spawn(process.execPath, args, { stdio: 'inherit' })
        child.once('error', reject)
        child.once('exit', (code, signal) => {
            if (code === 0) resolve()
            else reject(new Error(`dist/cli.js exited with ${signal ? `signal ${signal}` : `code ${code}`}`))
        })
    })
}

let rendered = 0
for (const { name, source } of examples) {
    const shouldRender = !selected || selected.has(name)
    if (shouldRender) {
        if (name === 'transparent-badge') transparentSources.push(source)
        else if (name.startsWith('nccl-')) ncclSources.push(source)
        else regularSources.push(source)
        rendered++
    }

    const code = await readFile(source, 'utf8')
    const outputs = themes.map((theme) => `${name}_${theme}.png`)

    if (code.includes('createScenes') || code.includes('createAnimation')) {
        if (shouldRender) animatedSources.push(source)
        outputs.push(...themes.map((theme) => `${name}_${theme}.gif`))
    }
    if (!shouldRender) {
        for (const output of outputs) {
            await access(join(outDir, output)).catch(() => {
                throw new Error(`Missing ${output}; run the full example render before using --only`)
            })
        }
    }

    manifest.push({
        name,
        source,
        outputs,
    })
}

await mkdir(outDir, { recursive: true })
const scratchRoot = await mkdtemp(join(tmpdir(), 'vizmatic-render-examples-'))
try {
    // Partition regular examples across parallel worker batches so Node, fonts, and Satori stay warm
    // and every batch writes its own temp manifest without contending on docs/assets/examples/manifest.json.
    const workerCount = Math.min(4, Math.max(1, cpus().length))
    type RenderBatch = { kind: 'png'; sources: string[]; extraArgs: string[] } | { kind: 'gif'; sources: string[] }
    const batches: RenderBatch[] = []
    // Queue animated GIF jobs first so the longest renders start immediately and PNG batches fill behind them.
    for (const source of animatedSources) {
        batches.push({ kind: 'gif', sources: [source] })
    }
    if (regularSources.length > 0) {
        const chunkCount = Math.min(workerCount, regularSources.length)
        const chunks: string[][] = Array.from({ length: chunkCount }, () => [])
        regularSources.forEach((source, index) => chunks[index % chunkCount]!.push(source))
        for (const chunk of chunks) batches.push({ kind: 'png', sources: chunk, extraArgs: ['--background', 'theme'] })
    }
    if (ncclSources.length > 0) {
        batches.push({ kind: 'png', sources: ncclSources, extraArgs: ['--no-crop', '--background', 'theme'] })
    }
    if (transparentSources.length > 0) {
        batches.push({ kind: 'png', sources: transparentSources, extraArgs: [] })
    }

    const gifManifestPath = join(outDir, 'gif-manifest.json')
    const previousGifs: Array<{ name: string }> = animatedSources.length > 0 && selected
        ? JSON.parse(await readFile(gifManifestPath, 'utf8'))
        : []
    const updatedGifs: Array<{ name: string }> = []

    const renderTasks: Promise<void>[] = []
    let nextBatch = 0
    const runWorker = async (workerId: number) => {
        for (;;) {
            const index = nextBatch++
            const batch = batches[index]
            if (!batch) return
            const batchOut = join(scratchRoot, `batch-${workerId}-${index}`)
            if (batch.kind === 'png') {
                await runCli([
                    'dist/cli.js',
                    'render',
                    ...batch.sources,
                    '--out',
                    batchOut,
                    '--theme',
                    themes.join(','),
                    ...batch.extraArgs,
                ])
                const files = await readdir(batchOut)
                await Promise.all(
                    files
                        .filter((file) => file.endsWith('.png'))
                        .map((file) => copyFile(join(batchOut, file), join(outDir, file))),
                )
            } else {
                await runCli([
                    'dist/cli.js',
                    'gif',
                    ...batch.sources,
                    '--out',
                    batchOut,
                    '--theme',
                    themes.join(','),
                    '--watermark',
                    'Vizmatic',
                    '--scale',
                    '1',
                ])
                const files = await readdir(batchOut)
                await Promise.all(
                    files
                        .filter((file) => file.endsWith('.gif'))
                        .map((file) => copyFile(join(batchOut, file), join(outDir, file))),
                )
                const batchGifs: Array<{ name: string }> = JSON.parse(await readFile(join(batchOut, 'gif-manifest.json'), 'utf8'))
                updatedGifs.push(...batchGifs)
            }
        }
    }

    const activeWorkers = Math.min(workerCount, batches.length)
    for (let i = 0; i < activeWorkers; i++) renderTasks.push(runWorker(i))
    await Promise.all(renderTasks)

    if (animatedSources.length > 0) {
        const gifsByName = new Map([...previousGifs, ...updatedGifs].map((entry) => [entry.name, entry]))
        const completeGifs = manifest
            .filter((entry) => entry.outputs.some((output) => output.endsWith('.gif')))
            .map((entry) => {
                const gif = gifsByName.get(entry.name)
                if (!gif) throw new Error(`Missing ${entry.name} GIF metadata; run the full example render`)
                return gif
            })
        await writeFile(gifManifestPath, `${JSON.stringify(completeGifs, null, 2)}\n`)
    }
} finally {
    await rm(scratchRoot, { recursive: true, force: true })
}

await writeFile(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
await writeFile(examplesReadmePath, generateExamplesReadme(manifest))
console.log(`rendered ${rendered} example frames in ${themes.join('/')} themes; indexed ${examples.length}`)
