import { access, readFile, writeFile } from 'fs/promises'
import { spawnSync } from 'child_process'
import { basename, join } from 'path'
import { exampleTitle, listGalleryExamples } from './gallery-examples'

const examplesDir = 'examples'
const examplesReadmePath = join(examplesDir, 'README.md')
const outDir = 'docs/assets/examples'
const galleryAssetUrl = 'https://bvolpato.github.io/vizmatic/assets/examples'
const themes = ['dark', 'light'] as const
const examples = await listGalleryExamples()
const onlyArgument = process.argv.slice(2).find((argument) => argument.startsWith('--only='))
const selected = onlyArgument ? new Set(onlyArgument.slice(7).split(',').filter(Boolean)) : undefined
if (selected) {
    const names = new Set(examples.map((example) => example.name))
    if (!selected.size || [...selected].some((name) => !names.has(name))) {
        throw new Error('--only requires comma-separated example names without the .tsx extension')
    }
}
let rendered = 0

const manifest: Array<{ name: string; source: string; outputs: string[] }> = []
const animatedSources: string[] = []

function previewFor(outputs: string[], theme: (typeof themes)[number]): string {
    return outputs.find((output) => output.endsWith(`_${theme}.gif`))
        ?? outputs.find((output) => output.endsWith(`_${theme}.png`))
        ?? outputs[0]
        ?? ''
}

function generateExamplesReadme(entries: typeof manifest): string {
    const rows = entries.map((entry) => {
        const title = exampleTitle(entry.name)
        const sourceFile = basename(entry.source)
        const dark = previewFor(entry.outputs, 'dark')
        const light = previewFor(entry.outputs, 'light')

        return `| [${title}](${sourceFile}) | <picture><source media="(prefers-color-scheme: dark)" srcset="${galleryAssetUrl}/${dark}" /><source media="(prefers-color-scheme: light)" srcset="${galleryAssetUrl}/${light}" /><img src="${galleryAssetUrl}/${light}" alt="${title} preview" width="720" /></picture> |`
    })

    return [
        '# Vizmatic examples',
        '',
        'Generated by `pnpm render:examples`. Edit the `.tsx` sources, then run that command again to refresh these previews.',
        '',
        'Rendered assets live on the [Vizmatic gallery](https://bvolpato.github.io/vizmatic/#gallery).',
        '',
        '| Example | Preview |',
        '|---|---|',
        ...rows,
        '',
    ].join('\n')
}

for (const { name, source } of examples) {
    const renderArgs = [
        'dist/cli.js',
        'render',
        source,
        '--out',
        outDir,
        '--theme',
        themes.join(','),
    ]
    if (name.startsWith('nccl-')) renderArgs.push('--no-crop')
    // Gallery images stay opaque, so they read on any page. The two exceptions show transparency itself.
    if (name !== 'transparent-badge') renderArgs.push('--background', 'theme')

    const shouldRender = !selected || selected.has(name)
    if (shouldRender) {
        const result = spawnSync(process.execPath, renderArgs, { stdio: 'inherit' })
        if (result.status !== 0) process.exit(result.status ?? 1)
        rendered++
    }

    const code = await readFile(source, 'utf8')
    const outputs = themes.map((theme) => `${name}_${theme}.png`)

    if (code.includes('createScenes') || code.includes('createAnimation')) {
        if (shouldRender) animatedSources.push(source)
        outputs.push(...themes.map((theme) => `${name}_${theme}.gif`))
    }
    if (!shouldRender) {
        for (const output of outputs) {
            await access(join(outDir, output)).catch(() => {
                throw new Error(`Missing ${output}; run the full example render before using --only`)
            })
        }
    }

    manifest.push({
        name,
        source,
        outputs,
    })
}

if (animatedSources.length > 0) {
    const gifManifestPath = join(outDir, 'gif-manifest.json')
    const previousGifs: Array<{ name: string }> = selected
        ? JSON.parse(await readFile(gifManifestPath, 'utf8'))
        : []
    const gifResult = spawnSync(process.execPath, [
        'dist/cli.js',
        'gif',
        ...animatedSources,
        '--out',
        outDir,
        '--theme',
        themes.join(','),
        '--watermark',
        'Vizmatic',
        '--scale',
        '1',
    ], {
        stdio: 'inherit',
    })

    if (gifResult.status !== 0) {
        process.exit(gifResult.status ?? 1)
    }

    if (selected) {
        const updatedGifs: Array<{ name: string }> = JSON.parse(await readFile(gifManifestPath, 'utf8'))
        const gifsByName = new Map([...previousGifs, ...updatedGifs].map(entry => [entry.name, entry]))
        const completeGifs = manifest.filter(entry => entry.outputs.some(output => output.endsWith('.gif'))).map(entry => {
            const gif = gifsByName.get(entry.name)
            if (!gif) throw new Error(`Missing ${entry.name} GIF metadata; run the full example render`)
            return gif
        })
        await writeFile(gifManifestPath, `${JSON.stringify(completeGifs, null, 2)}\n`)
    }
}

await writeFile(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
await writeFile(examplesReadmePath, generateExamplesReadme(manifest))
console.log(`rendered ${rendered} example frames in ${themes.join('/')} themes; indexed ${examples.length}`)
